'use strict';
const { createGas } = require('./gas-mock');
let checks = 0, fails = 0;
const ok = (c, m) => { checks++; if (!c) { fails++; console.error('✗ ' + m); } };
const G = createGas('pizarra42');
const base = { key: 'pizarra42', group: '1.º ESO C' };
ok(G.get({ ...base, action: 'ping' }).ok, 'ping');
ok(G.get({ key: 'mala', action: 'ping' }).error === 'clave', 'clave incorrecta rechazada');
ok(G.post({ ...base, action: 'score', alias: '=HACK()', mode: 'classic', score: 10 }).error === 'alias', 'alias con fórmula rechazado');
ok(G.post({ ...base, action: 'score', alias: 'Ninja7', mode: 'trampa', score: 10 }).error === 'modo', 'modo inválido');
ok(G.post({ ...base, action: 'score', alias: 'Ninja7', mode: 'classic', score: 99999999 }).error === 'puntos', 'puntos absurdos rechazados');
G.post({ ...base, action: 'score', alias: 'Ninja7', mode: 'classic', score: 1200, targets: 5 });
G.post({ ...base, action: 'score', alias: 'ninja7', mode: 'classic', score: 900 });
G.post({ ...base, action: 'score', alias: 'Pitagoras', mode: 'classic', score: 1500 });
G.post({ ...base, action: 'score', alias: 'Hipatia', mode: 'classic', score: 700 });
G.post({ key: 'pizarra42', group: '1.º ESO B', action: 'score', alias: 'Otro', mode: 'classic', score: 9999 });
const top = G.get({ ...base, action: 'top', mode: 'classic' });
ok(top.ok && top.rows.length === 3, 'ranking: un registro por alias y solo del grupo');
ok(top.rows[0].alias === 'Pitagoras' && top.rows[1].score === 1200 && top.rows[2].alias === 'Hipatia', 'ranking ordenado con la mejor puntuación de cada alias');
const r = G.post({ ...base, action: 'score', alias: 'Hipatia', mode: 'classic', score: 1300 });
ok(r.ok && r.puesto === 2, 'puesto devuelto tras guardar: ' + r.puesto);
// aventura: suma de estrellas de la mejor partida de cada nivel
G.post({ ...base, action: 'score', alias: 'Ninja7', mode: 'adventure', level: 1, score: 500, stars: 2 });
G.post({ ...base, action: 'score', alias: 'Ninja7', mode: 'adventure', level: 1, score: 400, stars: 3 });
G.post({ ...base, action: 'score', alias: 'Ninja7', mode: 'adventure', level: 2, score: 300, stars: 1 });
G.post({ ...base, action: 'score', alias: 'Hipatia', mode: 'adventure', level: 1, score: 900, stars: 3 });
ok(G.post({ ...base, action: 'score', alias: 'Hipatia', mode: 'adventure', score: 900, stars: 3 }).error === 'nivel', 'aventura exige nivel');
const ta = G.get({ ...base, action: 'top', mode: 'adventure' });
ok(ta.rows[0].alias === 'Ninja7' && ta.rows[0].stars === 4 && ta.rows[1].stars === 3, 'aventura: estrellas totales');
ok(JSON.stringify(G.get({ ...base, action: 'players' }).aliases) === JSON.stringify(['Hipatia', 'Ninja7', 'Pitagoras']), 'lista de jugadores del grupo');
// retos
ok(G.post({ ...base, action: 'duel', from: 'Ninja7', to: 'ninja7', code: 'ABCD-EFGH', score: 10 }).error === 'mismo', 'no puedes retarte a ti mismo');
ok(G.post({ ...base, action: 'duel', from: 'Ninja7', to: 'Hipatia', code: 'mal', score: 10 }).error === 'codigo', 'código de reto inválido');
const d = G.post({ ...base, action: 'duel', from: 'Ninja7', to: 'Hipatia', code: 'K7Q2-M9XA', score: 1840 });
ok(d.ok && d.id, 'reto creado');
let inbox = G.get({ ...base, action: 'duels', alias: 'hipatia' });
ok(inbox.incoming.length === 1 && inbox.incoming[0].from === 'Ninja7' && inbox.incoming[0].score === 1840, 'reto pendiente en la bandeja de Hipatia');
ok(G.get({ ...base, action: 'duels', alias: 'Ninja7' }).sent.length === 1, 'reto enviado visible para Ninja7');
ok(G.post({ ...base, action: 'duelResult', id: d.id, alias: 'Pitagoras', score: 5000 }).error === 'no_es_tuyo', 'otro alumno no puede responder el reto');
const res = G.post({ ...base, action: 'duelResult', id: d.id, alias: 'Hipatia', score: 2100 });
ok(res.ok && res.winner === 'Hipatia', 'resultado del reto: gana Hipatia');
ok(G.post({ ...base, action: 'duelResult', id: d.id, alias: 'Hipatia', score: 9000 }).error === 'ya_jugado', 'un reto solo se juega una vez');
inbox = G.get({ ...base, action: 'duels', alias: 'Ninja7' });
ok(inbox.history.length === 1 && inbox.history[0].winner === 'Hipatia' && inbox.history[0].reply === 2100, 'historial del retador con el resultado');
console.log(`Apps Script (simulado): ${checks} comprobaciones, ${fails} fallos`);
process.exit(fails ? 1 : 0);
